[Generator(LanguageNames.CSharp)]
public class SystemRegistrationGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Find all methods tagged with [System] using the exact metadata name
        var systemMethods = context.SyntaxProvider
        .ForAttributeWithMetadataName(
            fullyQualifiedMetadataName: "TECS.SystemAttribute",
            // 1. Fast filter: only look at attributes attached to methods
            predicate: static (node, cancellationToken) => node is MethodDeclarationSyntax,
            // 2. Transform: extract the semantic symbol
            transform: static (syntaxContext, cancellationToken) => (IMethodSymbol)syntaxContext.TargetSymbol
        )
        // 3. Final filter: ensure it's static and returns void
        .Where(symbol => symbol.IsStatic && symbol.ReturnsVoid);

        context.RegisterSourceOutput(systemMethods.Collect(), GenerateSystemBoilerplate);
    }

    private static void GenerateSystemBoilerplate(SourceProductionContext context, ImmutableArray<IMethodSymbol> methods)
    {
        if (methods.IsDefaultOrEmpty) return;

        var sourceBuilder = new StringBuilder();
        sourceBuilder.AppendLine("// <auto-generated />");
        sourceBuilder.AppendLine("using System;");
        sourceBuilder.AppendLine("using TECS;");
        sourceBuilder.AppendLine("using TECS.Event;");
        sourceBuilder.AppendLine("using TECS.Query;");
        sourceBuilder.AppendLine("using TECS.Commands;");
        sourceBuilder.AppendLine("using TECS.Systems;");
        sourceBuilder.AppendLine();
        sourceBuilder.AppendLine("namespace TECS");
        sourceBuilder.AppendLine("{");

        var generatedSignatures = new HashSet<string>();
        var delegatesAndBindingsBuilder = new StringBuilder();

        // Start the extension class
        sourceBuilder.AppendLine("    public static class AppExtensions");
        sourceBuilder.AppendLine("    {");

        foreach (var method in methods)
        {
            List<(string Sig,string Id,string Arg, string Setup)> queryTypes = new();
            // Extract the generic arguments of any Query<T> parameters
            foreach(var param in method.Parameters)
            {
                var t = param.Type as INamedTypeSymbol;
                if(t == null) continue;

                if(t.Name == "Query" && t.TypeArguments.Length == 1)
                {
                    var qType = t.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

                    queryTypes.Add( new (
                        $"Query<{qType}>",
                        qType.Replace("global::", "").Replace(".", "_"),
                        $"new Query<{qType}>(ecs)",
                        null
                    ));
                }
                
                else if (t.Name == "CommandBuffer")
                {
                    queryTypes.Add( new (
                       "CommandBuffer",
                        "CommandBuffer",
                        "cmd", // Pass the exact variable from the Run method,
                        null
                    ));
                }
                else if(t.Name == "EventWriter" && t.TypeArguments.Length == 1 )
                {
                    var qType = t.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                    string argName = $"writer_{queryTypes.Count}";
                    queryTypes.Add( new (
                        $"EventWriter<{qType}>",
                        qType.Replace("global::", "").Replace(".", "_") + "Write",
                        argName,
                        $"var {argName} = ecs.GetEventWriter<{qType}>();"
                        
                    ));
                }
                else if(t.Name == "EventReader" && t.TypeArguments.Length == 1 )
                {
                    var qType = t.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                     string argName = $"writer_{queryTypes.Count}";
                    queryTypes.Add( new (
                        $"EventReader<{qType}>",
                        qType.Replace("global::", "").Replace(".", "_") + "Read" ,
                        argName,
                        $"var {argName} = ecs.GetEventReader<{qType}>();"
                    ));
                }
                else if (t.Name == "Res" && t.TypeArguments.Length == 1)
{
                    var resType = t.TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                    string argName = $"res_{queryTypes.Count}";
                    queryTypes.Add((
                        $"Res<{resType}>",
                        resType.Replace("global::", "").Replace(".", "_") + "_Res",
                        argName,
                        $" var {argName} = new global::TECS.Query.Res<{resType}> {{ Value = ecs.GetResource<{resType}>() }};"
                ));
}

            }
            /*
            var queryTypes = method.Parameters
                .Select(p => p.Type as INamedTypeSymbol)

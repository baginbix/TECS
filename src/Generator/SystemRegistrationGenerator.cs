                            Arg = $"new Query<{qType}>(ecs)"
                        };
                    }
                    return null;

                })
                .Where(x => x is not null)
                .ToList();
            */
            if (queryTypes.Count == 0) continue;

            // Create a safe, unique string based on the query types 
            // e.g., "global__MyQuery_global__TrippleQuery"
            string uniqueId = string.Join("_", queryTypes.Select(q => q.Id));
            // Only generate the boilerplate once per unique parameter combination
            if (generatedSignatures.Add(uniqueId))
            {
               // Generate Extension Method for App
                sourceBuilder.AppendLine($"        public static App AddSystem(this App app, SystemDelegate_{uniqueId} system, SystemPhase phase = SystemPhase.Update)");
                sourceBuilder.AppendLine("        {");
                sourceBuilder.AppendLine($"            app.AddSystemBinding(new SystemBinding_{uniqueId}(system), phase);"); // <-- NEW (Safe!)
                sourceBuilder.AppendLine("            return app;");
                sourceBuilder.AppendLine("        }");
                sourceBuilder.AppendLine();

                // Generate AddSystemOnEnter
                sourceBuilder.AppendLine($"        public static App AddSystemOnEnter<TState>(this App app, TState state, SystemDelegate_{uniqueId} system) where TState : struct, Enum");
                sourceBuilder.AppendLine("        {");
                sourceBuilder.AppendLine($"            app.AddSystemOnEnter(state, new SystemBinding_{uniqueId}(system));"); // <-- NEW (Safe!)
                sourceBuilder.AppendLine("            return app;");
                sourceBuilder.AppendLine("        }");
                sourceBuilder.AppendLine();

                // Generate AddSystemOnUpdate
                sourceBuilder.AppendLine($"        public static App AddSystemOnUpdate<TState>(this App app, TState state, SystemDelegate_{uniqueId} system) where TState : struct, Enum");
                sourceBuilder.AppendLine("        {");
                sourceBuilder.AppendLine($"            app.AddSystemOnUpdate(state, new SystemBinding_{uniqueId}(system));"); // <-- NEW (Safe!)
                sourceBuilder.AppendLine("            return app;");
                sourceBuilder.AppendLine("        }");
                sourceBuilder.AppendLine();

                // Generate AddSystemOnExit
                sourceBuilder.AppendLine($"        public static App AddSystemOnExit<TState>(this App app, TState state, SystemDelegate_{uniqueId} system) where TState : struct, Enum");
                sourceBuilder.AppendLine("        {");
                sourceBuilder.AppendLine($"            app.AddSystemOnExit(state, new SystemBinding_{uniqueId}(system));");
                sourceBuilder.AppendLine("            return app;");
                sourceBuilder.AppendLine("        }");
                sourceBuilder.AppendLine();

                // Generate Custom Delegate (stored in the secondary builder)

                string typeParams = string.Join(", ", queryTypes.Select((p, i) => $"{p.Sig} p{i}"));
                delegatesAndBindingsBuilder.AppendLine($"    public delegate void SystemDelegate_{uniqueId}({typeParams});");
                
                // Generate System Binding
                delegatesAndBindingsBuilder.AppendLine($"    public class SystemBinding_{uniqueId} : SystemBinding");
                delegatesAndBindingsBuilder.AppendLine("    {");
                delegatesAndBindingsBuilder.AppendLine($"        private readonly SystemDelegate_{uniqueId} _func;");
                
                var bindingCtorBuilder = new StringBuilder();
                if(queryTypes.Count > 0)
                {
                    // System has 1 or more queries
                    bindingCtorBuilder.AppendLine("                List<Type> readsList = new List<Type>();");
                    bindingCtorBuilder.AppendLine("                List<Type> writesList = new List<Type>();");
                    
                    foreach (var q in queryTypes)
                    {
                        string fullExtensionPath = "global::" + q.Id.Replace('_', '.') + "Extensions";
                        string extName = $"{q.Id.Split('_').Last()}Extensions";
                        if(q.Sig != "CommandBuffer")
                        {
                            bindingCtorBuilder.AppendLine($"                readsList.AddRange({fullExtensionPath}.GetReads);");
                            bindingCtorBuilder.AppendLine($"                writesList.AddRange({fullExtensionPath}.GetWrites);");   
                        }
                    }

                    bindingCtorBuilder.AppendLine("                Reads = readsList.ToArray();");
                    bindingCtorBuilder.AppendLine("                Writes = writesList.ToArray();");
                }
                else
                {
                    // System only takes CommandBuffer / ECS (e.g. Startup Systems)
                    bindingCtorBuilder.AppendLine("                Reads = Array.Empty<Type>();");
                    bindingCtorBuilder.AppendLine("                Writes = Array.Empty<Type>();");
                }
                delegatesAndBindingsBuilder.AppendLine($$"""        
            public SystemBinding_{{uniqueId}}(SystemDelegate_{{uniqueId}} func){
                _func = func;
                {{bindingCtorBuilder}}
            }
            """);
                
                string setup = string.Join("\n                        ", queryTypes.Select(p => p.Setup));

                string instantiationParams = string.Join(", ", queryTypes.Select(q => q.Arg));
                delegatesAndBindingsBuilder.AppendLine($$"""        
                    public override void Run(ECS ecs , CommandBuffer cmd)
                    {
                        {{setup}}
                        _func({{instantiationParams}});
                        
                    }
                """);
                delegatesAndBindingsBuilder.AppendLine("    }");
                delegatesAndBindingsBuilder.AppendLine();
            }
        }

        // Close extension class
        sourceBuilder.AppendLine("    }");
        sourceBuilder.AppendLine();
        
        // Append all the generated delegates and classes
        sourceBuilder.Append(delegatesAndBindingsBuilder.ToString());
        
        // Close namespace
        sourceBuilder.AppendLine("}");

        context.AddSource("AppSystemExtensions.g.cs", sourceBuilder.ToString());
    }
}